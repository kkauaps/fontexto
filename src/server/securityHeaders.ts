/**
 * Single source of truth for the HTTP security headers.
 *
 *  - `public` (the static site on Cloudflare Pages): emitted as `_headers` by the Vite build.
 *  - `local` (the packaged executable / dev server on 127.0.0.1): the same policy minus the parts that only make
 *    sense over HTTPS (HSTS, upgrade-insecure-requests).
 *
 * The app loads nothing from other origins: scripts, styles, fonts, the pdf.js worker and wasm are all same-origin
 * files. pdf.js decodes some images with wasm, hence 'wasm-unsafe-eval' (and nothing broader: no 'unsafe-eval',
 * no 'unsafe-inline').
 */
export interface HeaderOptions {
  /** HTTPS deployment (adds HSTS and upgrade-insecure-requests). */
  https: boolean;
}

/** `scriptHashes`: sha256 sources for inline data blocks (the static pages' JSON-LD), e.g. "sha256-AbC…=". */
export function contentSecurityPolicy(opts: HeaderOptions, scriptHashes: string[] = []): string {
  for (const h of scriptHashes) if (!/^sha256-[A-Za-z0-9+/]{43}=$/.test(h)) throw new Error(`invalid CSP hash: ${h}`);
  const d = [
    "default-src 'self'",
    ["script-src 'self' 'wasm-unsafe-eval'", ...scriptHashes.map((h) => `'${h}'`)].join(' '),
    "style-src 'self'",
    "img-src 'self' data: blob:",
    "font-src 'self'",
    "connect-src 'self'",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'none'",
    "frame-ancestors 'none'",
    "form-action 'none'",
    "require-trusted-types-for 'script'",
    'trusted-types fontexto-pdfjs',
  ];
  if (opts.https) d.push('upgrade-insecure-requests');
  return d.join('; ');
}

export function securityHeaders(opts: HeaderOptions): Record<string, string> {
  const h: Record<string, string> = {
    'Content-Security-Policy': contentSecurityPolicy(opts),
    'X-Content-Type-Options': 'nosniff',
    'Referrer-Policy': 'no-referrer',
    'Permissions-Policy': 'accelerometer=(), autoplay=(), camera=(), clipboard-read=(), display-capture=(), geolocation=(), gyroscope=(), hid=(), magnetometer=(), microphone=(), midi=(), payment=(), publickey-credentials-get=(), serial=(), usb=(), xr-spatial-tracking=(), interest-cohort=()',
    'Cross-Origin-Opener-Policy': 'same-origin',
    'Cross-Origin-Resource-Policy': 'same-origin',
    'Cross-Origin-Embedder-Policy': 'require-corp',
    'X-Frame-Options': 'DENY',
    'X-Permitted-Cross-Domain-Policies': 'none',
  };
  if (opts.https) h['Strict-Transport-Security'] = 'max-age=63072000; includeSubDomains; preload';
  return h;
}

/** Cloudflare Pages `_headers` file content. */
export function pagesHeadersFile(): string {
  const lines: string[] = ['# Generated by the build from src/server/securityHeaders.ts. Do not edit by hand.', '/*'];
  for (const [k, v] of Object.entries(securityHeaders({ https: true }))) lines.push(`  ${k}: ${v}`);
  // Hashed build assets never change: cache hard. Everything else revalidates.
  lines.push('', '/assets/*', '  Cache-Control: public, max-age=31536000, immutable', '', '/fonts/*', '  Cache-Control: public, max-age=31536000, immutable', '', '/ort/*', '  Cache-Control: public, max-age=31536000, immutable', '', '/models/*', '  Cache-Control: public, max-age=31536000, immutable', '', '/tesseract/*', '  Cache-Control: public, max-age=31536000, immutable', '', '/.well-known/security.txt', '  Content-Type: text/plain; charset=utf-8', '');
  return lines.join('\n');
}
